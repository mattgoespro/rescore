const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const root = path.join(process.env.TEMP, 'rescore-installed-acceptance-20261014');
const read = name => JSON.parse(fs.readFileSync(path.join(root, name + '.json')));
const native = read('native-windows-report');
assert.equal(native.complete, true);
assert.equal(native.passed.length, 9);
const data = read('data-final'), before = read('baseline');
assert.equal(data.integrity[0].quick_check, 'ok');
assert.equal(data.libraryHash, before.libraryHash);
assert.equal(data.titleCount, before.titleCount);
const oldSettings = read('settings-before');
delete oldSettings.settings.region;
delete oldSettings.settings.imdbApiUrl;
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(process.env.APPDATA, 'Rescore', 'rescore.json'))), oldSettings);
const initial = read('registered-stopped');
assert.equal(initial.State, 'Stopped');
assert.equal(initial.StartMode, 'Manual');
const service = read('service-final');
assert.equal(service.State, 'Running');
assert.equal(service.StartMode, 'Auto');
assert.equal(service.StartName, 'NT SERVICE\\RescoreCatalogue');
assert.equal(read('before-identical-reinstall').ProcessId, read('after-identical-reinstall').ProcessId);
const recovered = read('final-crash-recovered');
assert.equal(recovered.result.status.phase, 'ready');
assert.equal(recovered.result.service.state, 'running');
assert.ok(recovered.result.statuses.some(s => s.phase === 'error'));
assert.equal(read('repair-brokers-before-close').length, 2);
assert.equal(read('close-with-elevated-worker').result.closed, true);
assert.match(read('settings-service-running').result.body, /Running.*Catalogue upkeep/);
assert.equal(read('real-library-roundtrip').result.writtenCount, 1);
assert.equal(read('final-real-browsing').result.libraryCount, 0);
assert.ok(read('final-real-browsing').result.searchCount > 0);
assert.ok(read('final-real-browsing').result.forYouCount > 0);
const installed = 'C:/Program Files/Rescore/resources/app.asar';
const built = 'dist/win-unpacked/resources/app.asar';
const hash = name => crypto.createHash('sha256').update(fs.readFileSync(name)).digest('hex');
assert.equal(hash(installed), hash(built));
for (const name of fs.readdirSync(root).filter(n => n.endsWith('.json'))) {
  const item = JSON.parse(fs.readFileSync(path.join(root, name)));
  if (item.errors) assert.deepEqual(item.errors, [], name);
  if (typeof item.ok === 'boolean') assert.equal(item.ok, true, name);
}
const result = { passed: true, time: new Date().toISOString(), titleCount: data.titleCount, libraryCount: data.libraryCount, libraryPreserved: true, supportedSettingsPreserved: true, installedArchiveHash: hash(installed), service, nativeScenarios: native.passed.length, desktopTests: 105, identicalReinstallPreservedPid: true, correctedAppCrashRecovery: true };
fs.writeFileSync(path.join(root, 'acceptance-summary.json'), JSON.stringify(result, null, 2));
console.log('PASS installed acceptance gate: data, settings, activation, elevated maintenance/closure, crash recovery, installer continuity, UI, and package identity');
